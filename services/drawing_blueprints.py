def get_curriculum_drawing(prompt: str) -> Optional[Dict[str, Any]]:
    """
    Matches user prompt to master handcrafted blueprints using token-aware matching.
    Returns None if no matching blueprint is found (falling back to frontier model generation).
    """
    if not prompt:
        return None
    raw = prompt.lower().strip()
    clean = re.sub(r'^(?:can you |could you |please |kindly )?(?:draw|sketch|illustrate|show me|how to draw)\s+(?:me\s+)?(?:a|an|the)?\s*', '', raw)
    clean_words_str = re.sub(r'[_\-]+', ' ', clean)
    words = set(re.findall(r'\b[a-z0-9]+\b', clean_words_str))
    clean_slug = re.sub(r'[\s\-]+', '_', clean).strip('_')

    # Direct key lookup
    if clean_slug in BLUEPRINTS:
        return BLUEPRINTS[clean_slug]

    # Priority Matchers for Recurring Class 10 Biology Diagrams (Life Processes)
    # A. Lime water experiment — exhaled air and atmospheric air
    if 'lime' in words or 'limewater' in words or 'pichkari' in words or ('exhaled' in words and 'air' in words):
        return BLUEPRINTS['lime_water_experiment']

    # B. Experiment to show carbon dioxide is essential for photosynthesis (Bell Jar + KOH)
    if 'koh' in words or 'hydroxide' in words or ('bell' in words and 'jar' in words) or (
        ('experiment' in words or 'essential' in words) and ('photosynthesis' in words or 'dioxide' in words or 'co2' in words)
    ):
        return BLUEPRINTS['co2_photosynthesis_experiment']

    # C. Open stomatal pore / Guard cells / Xylem & Phloem plant transport
    if {'stomata', 'stomatal', 'stoma', 'xylem', 'phloem', 'transpiration', 'translocation'}.intersection(words) or ('guard' in words and {'cell', 'cells', 'pore'}.intersection(words)):
        return BLUEPRINTS['open_stomatal_pore']

    # D. Double circulation in humans
    if ('double' in words and 'circulation' in words) or ('pulmonary' in words and 'systemic' in words):
        return BLUEPRINTS['double_circulation']

    # E. Structure of a nephron
    if {'nephron', 'nephrons', 'glomerulus', 'bowman'}.intersection(words):
        return BLUEPRINTS['nephron']

    # F. Human excretory system (vs single kidney cross-section)
    if {'excretory', 'excretion', 'ureter', 'ureters', 'urethra'}.intersection(words) or ('urinary' in words and 'bladder' in words):
        return BLUEPRINTS['human_excretory_system']

    # Specific Organ & Biological Subsystem Matchers (Prioritized before general anatomy)
    # 1. Heart Anatomy & Transportation
    if {'heart', 'cardiac', 'cardio', 'cardiovascular', 'haemoglobin', 'hemoglobin', 'circulation', 'blood', 'artery', 'arteries', 'vein', 'veins', 'aorta', 'ventricle', 'atrium', 'transportation'}.intersection(words):
        return BLUEPRINTS['heart_anatomy']

    # 2. Brain Anatomy
    if {'brain', 'cerebrum', 'cerebellum', 'cortex'}.intersection(words) and 'kidney' not in words and 'renal' not in words:
        return BLUEPRINTS['brain_anatomy']

    # 3. Eye Anatomy
    if {'eye', 'eyes', 'retina', 'cornea', 'vision'}.intersection(words):
        return BLUEPRINTS['eye_diagram']

    # 4. Neuron / Nerve Cell
    if {'neuron', 'neurons', 'synapse', 'axon'}.intersection(words) or ('nerve' in words and 'cell' in words):
        return BLUEPRINTS['neuron']

    # 5. Respiratory System / Lungs
    if {'respiratory', 'respiration', 'lungs', 'lung', 'trachea', 'bronchi', 'alveoli', 'breathing', 'aerobic', 'anaerobic'}.intersection(words):
        return BLUEPRINTS['respiratory_system']

    # 6. Digestive System / Stomach / Nutrition in Human Beings
    if {'digestive', 'digestion', 'alimentary', 'stomach', 'intestine', 'intestines', 'colon', 'saliva', 'amylase', 'bile', 'fats', 'fat', 'villi', 'peristalsis', 'nutrition', 'oesophagus', 'esophagus', 'pancreas', 'liver'}.intersection(words):
        return BLUEPRINTS['digestive_system']

    # 7. Kidney Anatomy (Single Kidney Cross-section)
    if {'kidney', 'kidneys', 'renal'}.intersection(words):
        return BLUEPRINTS['kidney_anatomy']

    # 7b. Chapter 5: Life Processes / Biology Default Diagram (Human Heart & Double Circulation)
    if {'life', 'processes', 'biology'}.intersection(words) or ('chapter' in words and '5' in words):
        return BLUEPRINTS['heart_anatomy']

    # 8. Human Anatomy / Body Silhouette (General)
    if {'anatomy', 'organs', 'skeleton'}.intersection(words) or ('human' in words and {'body', 'system', 'silhouette'}.intersection(words)):
        return BLUEPRINTS['human_anatomy']

    # 9. Lion / Feline Face
    if {'lion', 'lions', 'panthera'}.intersection(words):
        return BLUEPRINTS['lion_face']

    # 10. Elephant
    if {'elephant', 'elephants', 'proboscis', 'tusker', 'tusk', 'elephas'}.intersection(words):
        return BLUEPRINTS['elephant']

    # 11. Butterfly
    if {'butterfly', 'butterflies', 'caterpillar', 'moth', 'lepidoptera'}.intersection(words):
        return BLUEPRINTS['butterfly']

    # 12. Flower Anatomy
    if {'flower', 'flowers', 'pistil', 'stamen', 'petal', 'petals', 'angiosperm', 'carpel', 'hibiscus'}.intersection(words):
        return BLUEPRINTS['flower_anatomy']

    # 13. Photosynthesis / Autotrophic Nutrition
    if {'photosynthesis', 'chlorophyll', 'autotrophic', 'autotroph'}.intersection(words):
        return BLUEPRINTS['photosynthesis']

    # 14. Animal Cell / Mitochondria
    if ('animal' in words and 'cell' in words) or {'mitochondria', 'mitochondrion', 'pyruvate', 'cytoplasm'}.intersection(words) or 'animal_cell' in clean_slug:
        return BLUEPRINTS['animal_cell']

    # 15. Plant Cell
    if ('plant' in words and 'cell' in words) or 'chloroplast' in words or 'plant_cell' in clean_slug:
        return BLUEPRINTS['plant_cell']

    # 16. DNA Double Helix
    if {'dna', 'helix', 'nucleotide', 'nucleotides', 'chromosome'}.intersection(words):
        return BLUEPRINTS['dna_helix']

    # 17. Atom / Bohr Model (Strict token match to avoid collision with 'anatomy')
    if {'atom', 'atoms', 'bohr', 'atomic'}.intersection(words) or ('electron' in words and 'shell' in words):
        return BLUEPRINTS['atom_model']

    # 18. Electric Circuit
    if {'circuit', 'circuits', 'resistor', 'ammeter', 'voltmeter'}.intersection(words):
        return BLUEPRINTS['electric_circuit']

    # 19. Light Dispersion / Prism
    if {'prism', 'prisms', 'dispersion', 'spectrum', 'vibgyor'}.intersection(words):
        return BLUEPRINTS['prism_dispersion']

    # 20. Convex Mirror
    if 'convex' in words and 'mirror' in words:
        return BLUEPRINTS['convex_mirror']

    # 21. Bicycle
    if {'bicycle', 'bicycles', 'bike', 'bikes', 'cycle', 'cycling'}.intersection(words):
        return BLUEPRINTS['bicycle']

    # 22. Microscope
    if {'microscope', 'microscopes'}.intersection(words) or ('ocular' in words and 'lens' in words):
        return BLUEPRINTS['microscope']

    # 23. Car / Automobile
    if {'car', 'cars', 'automobile', 'automobiles', 'sedan', 'coupe', 'suv', 'supercar', 'vehicle'}.intersection(words):
        return BLUEPRINTS['car']

    # 24. Solar System / Planets
    if {'planets', 'planet', 'saturn', 'jupiter', 'orbits'}.intersection(words) or ('solar' in words and 'system' in words):
        return BLUEPRINTS['solar_system']

    # 25. Rocket / Spaceship
    if {'rocket', 'rockets', 'spaceship', 'spacecraft', 'shuttle'}.intersection(words) or ('launch' in words and 'vehicle' in words):
        return BLUEPRINTS['rocket']

    # 26. Volcano
    if {'volcano', 'volcanoes', 'magma', 'lava', 'eruption', 'stratovolcano'}.intersection(words):
        return BLUEPRINTS['volcano']

    return None
