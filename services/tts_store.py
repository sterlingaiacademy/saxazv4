"""Permanent store for generated narration audio (chapter summaries).

The chapter summary is the same text every time, so each sentence only needs to be
generated by Gemini once. After that the saved audio is played back instantly with
no TTS tokens spent.

Where audio is kept:
  * a local folder (fast, survives restarts on a normal server / your computer;
    on Vercel this is /tmp, which only lasts while an instance is warm)
  * Vercel Blob, when BLOB_READ_WRITE_TOKEN is set (survives deploys and cold starts)

Audio is raw 24 kHz 16-bit mono PCM, exactly what /api/tts/pcm-stream returns.
Changing CACHE_VERSION makes every sentence generate fresh once (e.g. after changing voices).
"""
from __future__ import annotations

import asyncio
import hashlib
import os
import tempfile

import httpx

CACHE_VERSION = "v1"

_ON_VERCEL = bool(os.environ.get("VERCEL"))
_PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCAL_DIR = os.environ.get("TTS_CACHE_DIR") or (
    os.path.join(tempfile.gettempdir(), "saxaz_tts_cache") if _ON_VERCEL else os.path.join(_PROJECT_ROOT, "tts_cache")
)
_BLOB_PREFIX = "tts_cache"


def _blob_token() -> str:
    return (os.environ.get("BLOB_READ_WRITE_TOKEN") or "").strip().strip('"')


def _blob_public_base(token: str) -> str | None:
    parts = token.split("_")
    if len(parts) >= 4 and parts[3]:
        return f"https://{parts[3].lower()}.public.blob.vercel-storage.com"
    return None


def make_key(voice: str, emotion: str, pace: str, text: str, keywords: list[str] | None = None) -> str:
    kw = ",".join(sorted(k.strip().lower() for k in (keywords or []) if k and k.strip()))
    raw = "|".join([CACHE_VERSION, voice or "", emotion or "", pace or "", kw, text or ""])
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _local_path(key: str) -> str:
    return os.path.join(LOCAL_DIR, key[:2], key + ".pcm")


def _read_local(key: str) -> bytes | None:
    try:
        with open(_local_path(key), "rb") as fh:
            data = fh.read()
        return data if len(data) >= 4 else None
    except OSError:
        return None


def _write_local(key: str, data: bytes) -> None:
    try:
        path = _local_path(key)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".part"
        with open(tmp, "wb") as fh:
            fh.write(data)
        os.replace(tmp, path)
    except OSError as e:
        print(f"[TTS store] local write failed: {e}")


async def get(key: str) -> bytes | None:
    """Saved audio for this sentence, or None if it has never been generated."""
    data = await asyncio.to_thread(_read_local, key)
    if data:
        return data
    token = _blob_token()
    base = _blob_public_base(token) if token else None
    if not base:
        return None
    try:
        async with httpx.AsyncClient(timeout=8.0) as client:
            resp = await client.get(f"{base}/{_BLOB_PREFIX}/{key}.pcm")
        if resp.status_code == 200 and len(resp.content) >= 4:
            await asyncio.to_thread(_write_local, key, resp.content)
            return resp.content
    except Exception as e:
        print(f"[TTS store] blob read failed: {e}")
    return None


async def put(key: str, data: bytes) -> None:
    """Save generated audio so it is never generated again."""
    if not data or len(data) < 4:
        return
    await asyncio.to_thread(_write_local, key, data)
    token = _blob_token()
    if not token:
        return
    try:
        async with httpx.AsyncClient(timeout=15.0) as client:
            resp = await client.put(
                f"https://vercel.com/api/blob/?pathname={_BLOB_PREFIX}/{key}.pcm",
                content=data,
                headers={
                    "authorization": f"Bearer {token}",
                    "x-api-version": "12",
                    "x-content-type": "application/octet-stream",
                    "x-vercel-blob-access": "public",
                    "x-add-random-suffix": "0",
                    "x-allow-overwrite": "1",
                    "x-cache-control-max-age": "31536000",
                },
            )
        if resp.status_code not in (200, 201):
            print(f"[TTS store] blob write HTTP {resp.status_code}: {resp.text[:120]}")
    except Exception as e:
        print(f"[TTS store] blob write failed: {e}")
